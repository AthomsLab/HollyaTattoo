export function getGalleryImageBySrc(src: string): GalleryImage {
  const image = galleryImages.find((item) => item.src === src)
  if (!image) {
    throw new Error(`Missing gallery image: ${src}`)
  }
  return image
}

export function getGalleryImagesBySrc(srcs: readonly string[]): GalleryImage[] {
  return srcs.map(getGalleryImageBySrc)
}

